"""Hands qualified company candidates to Wally -- as a proposal file, never
by editing a watchlist Wally actually screens.

Writes ``watchlists/macro_candidates_proposed.yaml`` in the exact schema
``wally/watchlist_loader.py`` already reads (a plain ``tickers:`` list, so
nothing breaks if Johnny copies entries straight into a real watchlist).
It is deliberately **not** added to ``wally/config.py::STANDARD_WATCHLISTS``
-- see docs/MICKYS_MACRO_ARCHITECTURE.md section 2 for why silently doing
that would be the wrong call to make on its own.
"""

from __future__ import annotations

from pathlib import Path

import yaml

from .schemas import CompanyCandidate

REPO_ROOT = Path(__file__).resolve().parent.parent
PROPOSAL_PATH = REPO_ROOT / "watchlists" / "macro_candidates_proposed.yaml"


def write_proposal(candidates: list[CompanyCandidate], path: Path = PROPOSAL_PATH) -> int:
    """Overwrites the proposal file with the current candidate set.
    Returns the number of tickers written. Not screened by Wally until a
    human copies entries into one of ``STANDARD_WATCHLISTS``."""
    tickers: list[str] = []
    notes: dict[str, str] = {}
    seen: set[str] = set()
    for c in sorted(candidates, key=lambda c: c.ticker):
        if c.ticker in seen:
            continue
        seen.add(c.ticker)
        suffix = ".AX" if c.is_asx and not c.ticker.endswith(".AX") else ""
        tickers.append(f"{c.ticker}{suffix}")
        notes[c.ticker] = (
            f"{c.exposure_type} of trend dossier {c.dossier_id}. {c.why_now}".strip()
        )

    payload = {
        "name": "Micky's Macro -- proposed candidates",
        "notes": (
            "Generated by Micky's Macro. NOT screened automatically -- this file is not in "
            "wally/config.py's STANDARD_WATCHLISTS. Review and copy entries into a real "
            "watchlist (with a considered buy price) to have Wally start screening them. "
            "See docs/MICKYS_MACRO_ARCHITECTURE.md."
        ),
        "tickers": tickers,
        "candidate_notes": notes,
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(yaml.safe_dump(payload, sort_keys=False, allow_unicode=True), encoding="utf-8")
    return len(tickers)
